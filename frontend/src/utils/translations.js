export const getTranslation = (lang, key) => {
  if (!key) return '';
  const currentLang = translations[lang] || translations.en;
  
  // 1. Direct key match
  if (currentLang[key]) return currentLang[key];
  if (translations.en[key]) return translations.en[key];

  // 2. Case-insensitive alias match (e.g. "Soil Moisture" -> "sensor_soil_moisture")
  const lower = String(key).trim().toLowerCase();
  const aliasKey = STRING_ALIASES[lower];
  if (aliasKey && currentLang[aliasKey]) {
    return currentLang[aliasKey];
  }

  return key;
};
